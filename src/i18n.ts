const translations: Record<string, Strings> = { es };

function steamLocale(): string {
  try {
    const steam = (window as any).LocalizationManager?.m_rgLocalesToUse?.[0];
    if (typeof steam === "string" && steam) return steam;
  } catch {
    // Not running inside Steam.
  }
  return navigator.language || "en";
}

// Steam asks for a restart when its language changes, so reading it once is enough.
export const locale = steamLocale();
const strings: Strings = translations[locale.toLowerCase().split("-")[0]] ?? en;

export function t(key: Key, values?: Record<string, string | number>) {
  let text = strings[key] ?? en[key];
  if (values) for (const [name, value] of Object.entries(values)) text = text.split(`{${name}}`).join(String(value));
  return text;
}

const MEDIA_KEYS: Record<string, Key> = {
  Audio: "mediaAudio",
  Contact: "mediaContact",
  File: "mediaFile",
  GIF: "mediaGif",
  Location: "mediaLocation",
  Photo: "mediaPhoto",
  Poll: "mediaPoll",
  Sticker: "mediaSticker",
  Video: "mediaVideo",
  "Video message": "mediaVideoMessage",
  "Voice message": "mediaVoiceMessage",
};

// The scraper reports media in English; the panel shows it in the interface language.
export function mediaLabel(media: string) {
  const key = MEDIA_KEYS[media];
  return key ? t(key) : media;
}
